const TEXTOS: Record<Idioma, Textos> = { es: ES, en: EN, pt: PT };
export const textosDe = (idioma: Idioma): Textos => TEXTOS[idioma] ?? ES;

const LOCALES: Record<Idioma, string> = { es: 'es-AR', en: 'en-US', pt: 'pt-BR' };
export const localeDe = (idioma: Idioma) => LOCALES[idioma] ?? 'es-AR';

/** Idioma del dispositivo si la carta lo ofrece; si no, español. */
export function idiomaInicial(ofrecidos: readonly Idioma[], navegador?: string): Idioma {
  const base = (navegador ?? '').slice(0, 2).toLowerCase() as Idioma;
  return ofrecidos.includes(base) ? base : 'es';
}

/** "lun a vie", "todos los días", "sáb y dom": días de la semana en el idioma elegido. */
export function describirDias(dias: number[], t: Textos): string {
  const orden = [...new Set(dias)].sort((a, b) => ((a + 6) % 7) - ((b + 6) % 7)); // lunes primero
  if (orden.length === 7) return t.todosLosDias;
  const posiciones = orden.map((d) => (d + 6) % 7);
  const seguidos = posiciones.every((p, i) => i === 0 || p === posiciones[i - 1] + 1);
  if (orden.length >= 3 && seguidos) return `${t.dias[orden[0]]}–${t.dias[orden[orden.length - 1]]}`;
  return orden.map((d) => t.dias[d]).join(', ');
}

/** Mensaje de la recomendación cuando no la redactó una IA. */
export function mensajeRecomendacion(
  r: { entendido: boolean; sinResultados: boolean; faltanEtiquetas: string[]; mensaje: string | null },
  t: Textos,
): string {
  if (r.mensaje) return r.mensaje;
  if (r.faltanEtiquetas.length) return t.faltanEtiquetas(r.faltanEtiquetas.map((c) => t.conceptoEtiqueta[c] ?? c).join(', '));
  if (r.sinResultados) return t.sinRecomendacion;
  return r.entendido ? t.recomiendo : t.contameMas;
}
